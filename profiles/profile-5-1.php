 <!-- ==================== WHAT IS THE 5/1 PROFILE? ==================== -->
 <section class="py-10 md:py-14 bg-gm-light">
 <div class="max-w-4xl mx-auto px-6">
 <h2 class="text-xl md:text-2xl font-bold text-gray-800 mb-6"> What Is the 5/1 Profile?
 </h2>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">The 5/1 Profile combines the <strong class="text-gray-800">Heretic</strong>, Line 5, with the <strong class="text-gray-800">Investigator</strong>, Line 1. This is one of the so-called <strong class="text-gray-800">Fixed Fate</strong> profiles, and it is often experienced as a configuration with strong impact and direction. The 5/1 carries the 5th line's projection field, meaning others may see them as someone who can solve problems, while the 1st line provides a deep investigative foundation beneath that projection.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">The conscious 5th line operates through <strong class="text-gray-800">projection and universalization</strong>. Others often project onto the 5/1 the ability to provide practical solutions. This projection field can be powerful and difficult to avoid. The 5/1 may be seen as either the answer or the disappointment, depending on whether the projection is fulfilled.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">The unconscious 1st line provides the foundation that makes the 5th line more credible. The 5/1 does not work best through guesswork. It tends to investigate deeply, building a strong knowledge base that supports its projected authority. This combination of projection and substance is what gives the 5/1 its distinctive effectiveness.</p>
 </div>
 </section>
 <!-- ==================== HOW THE 5 AND 1 WORK TOGETHER ==================== -->
 <section class="py-10 md:py-14 bg-white">
 <div class="max-w-4xl mx-auto px-6">
 <h2 class="text-xl md:text-2xl font-bold text-gray-800 mb-6">
How the 5 and 1 Work Together
 </h2>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">The 5/1 Profile combines outer projection with inner depth. Line 5 tends to attract attention, expectation, and the sense that others see it as capable of solving problems or providing practical leadership. Line 1, by contrast, needs a strong foundation. It wants to investigate thoroughly, understand deeply, and feel secure in what it stands on before stepping forward.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">This creates an important dynamic in the 5/1. Others may project certainty onto you before you feel ready. You may be called into responsibility, influence, or visibility while still needing time to study and build confidence. The healthiest expression of this profile does not come from trying to satisfy every projection, but from meeting outer demands with real substance.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">When these two lines work well together, the result is <strong class="text-gray-800">grounded leadership</strong>. The 5 brings reach, usefulness, and broad impact. The 1 brings depth, rigor, and foundational understanding. Together, they create someone who can offer practical solutions that are not superficial, but built on what has been thoroughly understood.</p>
 </div>
 </section>
 <!-- ==================== LIVING THE 5/1 ==================== -->
 <section class="py-10 md:py-14 bg-gm-light">
 <div class="max-w-4xl mx-auto px-6">
 <h2 class="text-xl md:text-2xl font-bold text-gray-800 mb-6"> Living the 5/1
 </h2>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">The 5/1 must learn to manage projection while protecting the integrity of its foundation. The 5th line attracts expectation, responsibility, and visibility, while the 1st line needs time to investigate, prepare, and build real confidence. This can create pressure to step forward before the inner groundwork feels complete.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">This is why Strategy and Authority matter so much for the 5/1. They help you recognize which roles, demands, and opportunities are actually correct for you, and which ones are based on projection alone. When a 5/1 responds from a solid foundation, its practical impact can be enormous. When it tries to meet expectations without enough depth or clarity, the result is often strain, disappointment, or mistrust.</p>

 <div class="bg-gm-card-active border-l-4 border-gm-purple rounded-r-lg p-5 my-6">
 <p class="text-xs font-semibold text-gm-purple uppercase tracking-widest mb-2">Key Insight</p>
 <p class="text-gm-text text-sm leading-relaxed italic">Remember: your Profile operates within your Type and Authority. A 5/1 Generator lives this profile very differently from a 5/1 Projector. The Profile describes your role, while your Type and Authority describe how you enter into that role correctly.</p>
 </div>
 </div>
 </section>
 <!-- ==================== THE 5/1 IN RELATIONSHIPS ==================== -->
 <section class="py-10 md:py-14 bg-white">
 <div class="max-w-4xl mx-auto px-6">
 <h2 class="text-xl md:text-2xl font-bold text-gray-800 mb-6"> The 5/1 in Relationships
 </h2>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">In relationships, 5/1s often need to navigate both projection and depth. The 5th line can attract strong expectations from partners, who may see the 5/1 as especially capable, steady, or able to solve problems. This can create pressure if the relationship is built more on what is projected than on who the person really is.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">At the same time, the 1st line needs security, understanding, and a solid foundation. A 5/1 often wants to know what a relationship is built on and feel confident in its depth before fully relaxing into it. They may need time to investigate, understand, and trust what is actually there.</p>
 <p class="text-gm-text text-sm md:text-base leading-relaxed mb-4">Healthy relationships for a 5/1 depend on <strong class="text-gray-800">clarity, honesty, and realistic expectations</strong>. They do best with partners who see beyond projection, respect their need for depth, and value the practical support and grounded insight they genuinely bring. When seen clearly, a 5/1 can be deeply dependable, protective, and useful in relationship.</p>
 </div>
